import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
import {cardioEffortFromRpe,workoutCardioEffort,cardioLoad,preferredCardioMetric,compareCardioAtMatchedEffort} from '../cardio-analytics.js';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const app=fs.readFileSync(path.join(root,'app.js'),'utf8');
const sw=fs.readFileSync(path.join(root,'sw.js'),'utf8');
assert.ok(sw.includes('"./cardio-analytics.js"'),'Cardio analytics must work offline');
assert.ok(app.includes('Target duration (minutes)'));
for (const id of ['f-sets-wrap','f-rest-wrap','f-ramp-wrap','f-exercise-type-wrap','f-cardio-minutes']) assert.ok(app.includes(id));
assert.equal(cardioEffortFromRpe(null).key,'unknown');
assert.equal(cardioEffortFromRpe(2).key,'easy');
assert.equal(cardioEffortFromRpe(5).key,'moderate');
assert.equal(cardioEffortFromRpe(8).key,'hard');
assert.equal(cardioEffortFromRpe(10).key,'veryhard');
assert.equal(cardioLoad(30,6),180);
assert.equal(cardioLoad(30,null),null);
const session={id:1};
const completed=(id,rpe,seconds)=>({sessionExerciseId:id,status:'COMPLETE',sessionRpe:rpe,actualDurationSeconds:seconds});
const cardioState={session_exercises:[{id:11,sessionId:1,trackingMode:'CARDIO'},{id:12,sessionId:1,trackingMode:'CARDIO'}],performed_sets:[completed(11,4,600),completed(12,8,1800)]};
assert.deepEqual({mode:workoutCardioEffort(cardioState,session).mode,key:workoutCardioEffort(cardioState,session).effort.key},{mode:'cardio',key:'hard'});
assert.equal(workoutCardioEffort({...cardioState,session_exercises:[...cardioState.session_exercises,{id:13,sessionId:1,trackingMode:'WEIGHT_REPS'}],performed_sets:[...cardioState.performed_sets,completed(13,null,0)]},session).mode,'mixed');
assert.equal(workoutCardioEffort({session_exercises:[{id:1,sessionId:1,trackingMode:'CARDIO'}],performed_sets:[completed(1,null,600)]},session).effort.key,'unknown');
const r=(distanceKm,secs,rpe,power=null)=>({completedSets:1,totalDistanceKm:distanceKm,totalDurationSeconds:secs,sessionRpe:rpe,averagePowerWatts:power});
assert.equal(preferredCardioMetric([r(0,1800,5),r(0,1900,5)]),'DURATION');
assert.equal(preferredCardioMetric([r(5,1800,5),r(5,1700,5)]),'PACE');
assert.equal(preferredCardioMetric([r(0,1800,5,160),r(0,1900,5,170)]),'POWER');
assert.ok(compareCardioAtMatchedEffort([r(5,1800,5),r(5,1700,5)],'PACE').changePct>0);
assert.equal(compareCardioAtMatchedEffort([r(5,1800,2),r(5,1700,8)],'PACE'),null);
assert.equal(compareCardioAtMatchedEffort([r(5,1800,5),r(10,1700,5)],'PACE'),null);
assert.ok(compareCardioAtMatchedEffort([r(0,1800,5,150),r(0,1830,6,160)],'POWER').changePct>0);
assert.equal(compareCardioAtMatchedEffort([r(0,1800,5,150),r(0,2500,5,160)],'POWER'),null);
// An app start must not be blocked by unresolved WebAudio or slow IndexedDB saving.
const beginning=app.indexOf('async function startWorkout('),ending=app.indexOf('\nfunction runtimeNeedsRecovery',beginning);
assert.ok(beginning>0&&ending>beginning);
const source=app.slice(beginning,ending);
let navigated='',persisted=false;
const state={app_state:{maxRampUpSets:3},workout_sessions:[],session_exercises:[],performed_sets:[],runtime:null};
const ctx={state,now:()=>1000,uid:arr=>arr.length+1,activeSession:()=>null,toast:()=>{},getWorkout:()=>({id:4,name:'Cardio day'}),getTemplateExercises:()=>[{id:5,userExerciseId:'run',name:'Running',equipment:'CARDIO',trackingMode:'CARDIO',sets:1,reps:0,targetSeconds:1800,restSeconds:0,position:0,initialWeightKg:0}],getUserExercise:()=>({id:'run',equipment:'CARDIO',trackingMode:'CARDIO'}),templateDisplayName:te=>te.name,Equipment:{BODYWEIGHT:'BODYWEIGHT',CARDIO:'CARDIO',OTHER:'OTHER'},DumbbellLoad:{SINGLE:'SINGLE'},TrackingMode:{CARDIO:'CARDIO',TIME_ONLY:'TIME_ONLY',WEIGHT_REPS:'WEIGHT_REPS'},ExerciseType:{MODERATE_COMPOUND:'MODERATE_COMPOUND'},RampMode:{AUTO:'AUTO'},recommendRamp:()=>[],snapSelectable:v=>v,enableAudio:()=>new Promise(()=>{}),requestWakeLock:()=>{},nav:r=>{navigated=r;},persist:()=>{persisted=true;return new Promise(()=>{});},alertDialog:()=>{},console};
vm.createContext(ctx);vm.runInContext(source,ctx);
void ctx.startWorkout(4);
assert.equal(navigated,'active','Start must navigate to workout immediately, despite audio and pending save');
assert.equal(persisted,true);
assert.equal(state.performed_sets.length,1);
assert.equal(state.performed_sets[0].targetDurationSeconds,1800);
console.log('OK: cardio effort/load, comparison guards, offline module and immediate workout-start transition');
